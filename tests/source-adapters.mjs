import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {inventoryCanonicalInput,createCanonicalLedger} from '../scripts/lib/canonical-source-ledger.mjs';
const require=createRequire(path.join(process.env.RUNTIME_NODE_MODULES,'package.json'));
const imported=await import(require.resolve('jszip')),JSZip=imported.default||imported;
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'mint-source-adapters-'));
const docx=new JSZip();
docx.file('word/document.xml','<w:document><w:body><w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>原始标题</w:t></w:r></w:p><w:tbl><w:tr><w:tc><w:p><w:r><w:t>预计</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>80万元</w:t></w:r></w:p></w:tc></w:tr></w:tbl><w:p><w:r><w:t>仅在试点范围</w:t></w:r></w:p></w:body></w:document>');
docx.file('word/media/image1.png',Buffer.from([1,2,3]));
const docxFile=path.join(dir,'source.docx');fs.writeFileSync(docxFile,await docx.generateAsync({type:'nodebuffer'}));
const runs=await Promise.all([1,2,3].map(async()=>createCanonicalLedger([await inventoryCanonicalInput({path:docxFile,sourceOrigin:'raw-source'})])));
assert.deepEqual(runs[0],runs[1]);assert.deepEqual(runs[0],runs[2]);
assert.deepEqual(runs[0].units.map(u=>u.kind),['heading','table-cell','table-cell','paragraph','image']);
const book=new JSZip(),file=path.join(dir,'source.xlsx');
book.file('xl/worksheets/sheet1.xml','<worksheet><sheetData><row><c r="A1" t="inlineStr"><is><t>件数</t></is></c><c r="B1"><v>12</v></c></row></sheetData></worksheet>');
fs.writeFileSync(file,await book.generateAsync({type:'nodebuffer'}));
const inventory=await inventoryCanonicalInput({path:file,sourceOrigin:'raw-source'});
assert.deepEqual(inventory.blocks.map(b=>[b.id,b.text]),[['xl/worksheets/sheet1.xml!A1','件数'],['xl/worksheets/sheet1.xml!B1','12']]);
book.file('xl/worksheets/sheet1.xml','<worksheet><c r="A1" s="1"><v>45000</v></c></worksheet>');
fs.writeFileSync(file,await book.generateAsync({type:'nodebuffer'}));
await assert.rejects(()=>inventoryCanonicalInput({path:file,sourceOrigin:'raw-source'}),/FORMAT_REVIEW_REQUIRED/);
console.log('DOCX anchors stable in three runs; XLSX cells preserved; formatted serial cannot masquerade as displayed value');
