import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createCanonicalLedger,inventoryCanonicalInput,verifyCanonicalLedger,canonicalCoverage} from '../scripts/lib/canonical-source-ledger.mjs';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'mint-canonical-'));
const file=path.join(dir,'source.txt');fs.writeFileSync(file,'# 计划\n主体甲预计全年80万元，验收后启动。\n主体乙仅在试验范围内使用。');
const descriptor={path:file,sourceOrigin:'raw-source'};
const runs=await Promise.all([1,2,3].map(async()=>createCanonicalLedger([await inventoryCanonicalInput(descriptor)])));
assert.deepEqual(runs[0],runs[1]);assert.deepEqual(runs[0],runs[2]);assert.equal(runs[0].canonicalFactsTotal,3);
await verifyCanonicalLedger(runs[0]);
assert.throws(()=>createCanonicalLedger([{...runs[0].inputs[0],sourceOrigin:'derived',blocks:[]}]),/INVALID/);
const ledger=runs[0],source={sourceUnits:ledger.units};
const second=path.join(dir,'second.txt');fs.writeFileSync(second,'另一个原始单元');
const inputs=[await inventoryCanonicalInput(descriptor),await inventoryCanonicalInput({path:second,sourceOrigin:'raw-source'})];
assert.deepEqual(createCanonicalLedger(inputs),createCanonicalLedger([...inputs].reverse()),'input listing order cannot change denominator or IDs');
const task=path.join(dir,'task.json'),taskInput={path:task,sourceOrigin:'task-card',selector:'/originalText'};
fs.writeFileSync(task,JSON.stringify({originalText:'甲预计全年80万元',visualTone:'plain'}));
const first=createCanonicalLedger([await inventoryCanonicalInput(taskInput)]);
fs.writeFileSync(task,JSON.stringify({originalText:'甲预计全年80万元',visualTone:'executive',extraDesign:'不要拆页'}));
const styled=createCanonicalLedger([await inventoryCanonicalInput(taskInput)]);
assert.equal(first.sha256,styled.sha256,'design metadata cannot change canonical identity');
assert.deepEqual(first.units,styled.units);
const mappings=Object.fromEntries(ledger.units.map(u=>[u.id,[{text:u.text}]]));
assert.equal(canonicalCoverage(ledger,source,{passed:true,mappings}).canonicalFactsVisible,3);
assert.equal(canonicalCoverage(ledger,{sourceUnits:source.sourceUnits.slice(1)},{passed:true,mappings}).passed,false);
assert.equal(canonicalCoverage(ledger,{sourceUnits:source.sourceUnits.slice(1),approvedOmissions:[{sourceUnitId:ledger.units[0].id,approved:true,reason:'用户明确批准'}]},{passed:true,mappings}).canonicalFactsOmitted,1);
fs.appendFileSync(file,'\n新增事实');await assert.rejects(()=>verifyCanonicalLedger(ledger),/CHANGED/);
console.log('Canonical ledger: stable across three runs; omissions and changed inputs rejected');
